#!/usr/bin/env bash
# Managed-By: liqun-helper
set -euo pipefail

INSTANCE="${1:-}"
if [[ -z "${INSTANCE}" ]]; then
    echo "Usage: $0 <rule-instance-name>" >&2
    exit 2
fi

if [[ ! "${INSTANCE}" =~ ^[a-zA-Z0-9][a-zA-Z0-9._-]{0,62}$ ]]; then
    echo "Invalid instance name: ${INSTANCE}" >&2
    exit 2
fi

INSTALL_ENV="/usr/local/lib/liqun-helper/install.env"
STATE_DIR="${LIQUN_HELPER_STATE_DIR:-/var/lib/liqun-helper}"
if [[ -f "${INSTALL_ENV}" && ! -L "${INSTALL_ENV}" ]]; then
    while IFS='=' read -r k v; do
        if [[ "${k}" == "LIQUN_HELPER_STATE_DIR" && -n "${v}" ]]; then
            STATE_DIR="${v}"
        fi
    done < "${INSTALL_ENV}"
fi

ENV_FILE="${STATE_DIR}/realm/${INSTANCE}.env"
CONF_FILE="${STATE_DIR}/realm/${INSTANCE}.toml"

if [[ -L "${ENV_FILE}" || ! -f "${ENV_FILE}" ]]; then
    echo "Missing or unsafe realm env file: ${ENV_FILE}" >&2
    exit 1
fi
if [[ -L "${CONF_FILE}" || ! -f "${CONF_FILE}" ]]; then
    echo "Missing or unsafe realm config file: ${CONF_FILE}" >&2
    exit 1
fi

ENV_HDR="$(head -n 1 "${ENV_FILE}" || true)"
CONF_HDR="$(head -n 1 "${CONF_FILE}" || true)"
if [[ "${ENV_HDR}" != "# Generated by liqun-helper"* ]]; then
    echo "Realm env file lacks managed header: ${ENV_FILE}" >&2
    exit 1
fi
if [[ "${CONF_HDR}" != "# Generated by liqun-helper for rule: ${INSTANCE}" ]]; then
    echo "Realm config file lacks expected rule header: ${CONF_FILE}" >&2
    exit 1
fi

REALM_BIN=""
while IFS='=' read -r key val; do
    if [[ "${key}" == "REALM_BIN" ]]; then
        REALM_BIN="${val}"
        break
    fi
done < "${ENV_FILE}"

if [[ -z "${REALM_BIN}" || ! -x "${REALM_BIN}" ]]; then
    echo "Realm binary is missing or not executable: ${REALM_BIN}" >&2
    exit 1
fi

exec "${REALM_BIN}" -c "${CONF_FILE}"
