class ApplyError(RuntimeError):
    """Raised when applying a rule fails (with staged rollback details included)."""


@dataclass
class PreflightReport:
    """Structured preflight inspection result."""

    rule: RuleConfig
    line: LineConfig
    realm_info: RealmBinaryInfo
    listen_interface: str
    route_result: RouteGetResult
    unit_name: str
    fixed_ip_check: Optional[FixedIpCheckResult] = None
    stale_ip_warning: Optional[str] = None
    return_route: Optional[RouteGetResult] = None


def _rule_paths(global_cfg: GlobalConfig, rule_name: str) -> Dict[str, Path]:
    validate_rule_name(rule_name)
    rules_dir = Path(global_cfg.tool.rules_dir)
    state_dir = Path(global_cfg.tool.state_dir)
    return {
        "stored_rule": ensure_safe_subpath(rules_dir, rules_dir / f"{rule_name}.toml"),
        "realm_toml": ensure_safe_subpath(state_dir, state_dir / "realm" / f"{rule_name}.toml"),
        "realm_env": ensure_safe_subpath(state_dir, state_dir / "realm" / f"{rule_name}.env"),
        "state_json": ensure_safe_subpath(state_dir, state_dir / "state" / f"{rule_name}.json"),
    }


def _render_realm_env(realm_bin: str) -> str:
    return f"# Generated by leikwan_tools\nREALM_BIN={realm_bin}\n"


def _load_state_json(path: Path) -> Dict[str, Any]:
    if not path.is_file() or path.is_symlink():
        return {}
    try:
        state = json.loads(path.read_text(encoding="utf-8"))
        return state if isinstance(state, dict) else {}
    except (OSError, json.JSONDecodeError):
        return {}


def _applied_line(global_cfg: GlobalConfig, rule: RuleConfig, state: Dict[str, Any]) -> Optional[LineConfig]:
    snapshot = state.get("applied_line")
    if snapshot is not None:
        try:
            line = LineConfig(**snapshot)
        except (TypeError, ConfigError) as exc:
            raise ConfigError(f"规则 {rule.name!r} 的已应用线路记录无效，请重新应用") from exc
        if line.name != rule.line or line.is_ipv6 != rule.remote_is_ipv6:
            raise ConfigError(f"规则 {rule.name!r} 的已应用线路与规则不一致，请重新应用")
        return line

    line = global_cfg.lines.get(rule.line)
    source, interface = state.get("through"), state.get("egress_interface")
    if line and isinstance(source, str) and source and isinstance(interface, str) and interface:
        return replace(line, source_ip=source, interface=interface, family="")
    return line


def _applied_listen_interface(global_cfg: GlobalConfig, rule: RuleConfig, state: Dict[str, Any]) -> str:
    if rule.direct_ipv6:
        return ""
    return state.get("listen_interface", global_cfg.ingress.listen_interface)


def _line_route_settings(line: LineConfig) -> Tuple[str, str, str, str, Optional[int]]:
    return line.family, line.source_ip, line.interface, line.gateway, line.table


def _is_rule_enabled_record(global_cfg: GlobalConfig, rule_name: str) -> bool:
    unit = unit_name_for_rule(global_cfg.tool.systemd_unit_template, rule_name)
    try:
        if systemd_is_enabled(unit):
            return True
    except Exception:
        pass
    state = _load_state_json(_rule_paths(global_cfg, rule_name)["state_json"])
    return bool(state.get("enabled", False))


def _check_managed_rule_port_conflicts(global_cfg: GlobalConfig, target_rule: RuleConfig) -> None:
    """Prevent two enabled managed rules from claiming the same listen_ip:listen_port even if one is stopped."""
    rules_dir = Path(global_cfg.tool.rules_dir)
    if not rules_dir.is_dir():
        return
    for item in sorted(rules_dir.glob("*.toml")):
        if item.stem == target_rule.name:
            continue
        try:
            other = load_rule_config(str(item), default_domain=global_cfg.ingress.default_domain)
        except ConfigError:
            continue
        if other.name == target_rule.name:
            continue
        if other.listen_ip == target_rule.listen_ip and other.listen_port == target_rule.listen_port:
            if _is_rule_enabled_record(global_cfg, other.name):
                raise PreflightError(
                    f"监听端口 {target_rule.listen_endpoint} 与已启用的托管规则 "
                    f"{other.name!r} 冲突，请先停用或修改其中一条规则。"
                )


def _assert_live_install_intact(global_cfg: GlobalConfig) -> None:
    """Verify live systemd host installation wasn't concurrently uninstalled or replaced."""
    if Path("/run/systemd/system").is_dir():
        ok, reason = verify_template_unit_owned(TEMPLATE_UNIT_PATH)
        if not ok:
            raise OwnershipError(f"工具安装状态异常，拒绝写操作: {reason}")
    if global_cfg.config_path and not Path(global_cfg.config_path).is_file():
        raise ConfigError(f"主配置文件已不存在（可能刚被卸载）: {global_cfg.config_path}")


def _assert_rule_owned_for_mutation(global_cfg: GlobalConfig, rule_name: str) -> str:
    """Verify an existing rule is actually owned by leikwan_tools before modifying/stopping/deleting it."""
    kind, detail = check_rule_ownership(
        rules_dir=global_cfg.tool.rules_dir,
        state_dir=global_cfg.tool.state_dir,
        rule_name=rule_name,
        unit_template=global_cfg.tool.systemd_unit_template,
    )
    if kind == "unowned":
        raise OwnershipError(f"拒绝操作非本工具管理的规则或服务 {rule_name!r}: {detail}")
    return kind


def _verify_return_route(
    global_cfg: GlobalConfig, listen_ip: str, listen_iface: str, link_states, addr_map
) -> RouteGetResult:
    if ":" in listen_ip:
        if listen_iface in link_states:
            operstate, flags = link_states[listen_iface]
            if "UP" not in flags or operstate == "DOWN":
                raise PreflightError(
                    f"公网 IPv6 {listen_ip} 所在网卡 {listen_iface} 状态异常: state={operstate}, flags={flags}"
                )
        command = ["ip", "-6", "route", "get", PUBLIC_ROUTE_PROBE_IPV6, "from", listen_ip]
        result = run_cmd(command)
        route = parse_route_get_output(PUBLIC_ROUTE_PROBE_IPV6, listen_ip, result.stdout, command)
        if result.returncode or not route.dev:
            raise PreflightError(f"公网 IPv6 {listen_ip} 无回程路由: {result.stderr.strip() or route.raw_output}")
        return route

    expected_iface = global_cfg.ingress.listen_interface or listen_iface
    try:
        if listen_iface != expected_iface:
            raise PreflightError(f"监听 IPv4 {listen_ip} 位于 {listen_iface}，入口要求 {expected_iface}")
        line = next(
            (item for item in global_cfg.lines.values() if not item.is_ipv6 and item.source_ip == listen_ip),
            None,
        )
        if line is None:
            line = next(
                (item for item in global_cfg.lines.values() if not item.is_ipv6 and item.interface == listen_iface),
                None,
            )
        if line is not None:
            if line.interface != listen_iface:
                raise PreflightError(f"监听线配置为 {line.interface}，监听 IPv4 实际位于 {listen_iface}")
            line = replace(line, source_ip=listen_ip)
            verify_line_interface_and_source(line, link_states, addr_map)
            return verify_egress_route(line, PUBLIC_ROUTE_PROBE_IP)

        command = ["ip", "-4", "route", "get", PUBLIC_ROUTE_PROBE_IP, "from", listen_ip]
        result = run_cmd(command)
        route = parse_route_get_output(PUBLIC_ROUTE_PROBE_IP, listen_ip, result.stdout, command)
        if result.returncode or route.dev != listen_iface:
            raise PreflightError(result.stderr.strip() or route.raw_output or "无回程路由")
        return route
    except PreflightError as exc:
        raise PreflightError(f"入口回程校验失败 ({listen_ip}@{expected_iface}): {exc}") from exc


def preflight_rule(
    global_cfg: GlobalConfig,
    rule: RuleConfig,
    check_dns: bool = False,
    allow_non_dns: bool = False,
    dns_server: str = "",
) -> PreflightReport:
    """Validate all prerequisites (ownership, Realm, NIC, policy route, port conflict, fixed IP)."""
    validate_rule_name(rule.name)
    if rule.line not in global_cfg.lines:
        available = ", ".join(sorted(global_cfg.lines))
        raise PreflightError(
            f"规则 {rule.name!r} 指定的出口线路 {rule.line!r} 不存在（已配置线路: {available}）"
        )
    line = global_cfg.lines[rule.line]
    if rule.remote_is_ipv6 != line.is_ipv6:
        matching = ", ".join(
            sorted(name for name, lc in global_cfg.lines.items() if lc.is_ipv6 == rule.remote_is_ipv6)
        ) or "(无)"
        raise PreflightError(
            f"规则 {rule.name!r} 落地地址族 ({rule.remote_family}: {rule.remote_endpoint}) "
            f"与出口线路 {rule.line!r} ({line.family}: {line.source_ip}@{line.interface}) 不匹配；"
            f"可用的 {rule.remote_family} 出口线路: {matching}"
        )

    paths = _rule_paths(global_cfg, rule.name)
    unit_name = unit_name_for_rule(global_cfg.tool.systemd_unit_template, rule.name)
    if paths["stored_rule"].exists():
        _assert_rule_owned_for_mutation(global_cfg, rule.name)
        prev_rule = load_rule_config(
            str(paths["stored_rule"]), default_domain=global_cfg.ingress.default_domain
        )
        prev_fixed_ip = prev_rule.ingress_fixed_ip
    else:
        assert_rule_slot_available_for_create(
            rules_dir=global_cfg.tool.rules_dir,
            state_dir=global_cfg.tool.state_dir,
            rule_name=rule.name,
            unit_template=global_cfg.tool.systemd_unit_template,
        )
        prev_fixed_ip = ""

    fixed_check: Optional[FixedIpCheckResult] = None
    stale_warn: Optional[str] = None
    effective_dns = dns_server or global_cfg.ingress.dns_server
    if not rule.direct_ipv6 and (rule.ingress_fixed_ip or check_dns):
        fixed_check = evaluate_fixed_ip_policy(
            domain=rule.ingress_domain,
            new_fixed_ip=rule.ingress_fixed_ip,
            prev_fixed_ip=prev_fixed_ip,
            dns_server=effective_dns,
            allow_non_dns=allow_non_dns,
        )
        if not fixed_check.allowed:
            raise PreflightError(fixed_check.error or "固定公网 IP 校验失败")
        stale_warn = fixed_check.warning

    realm_info = discover_realm_binary(global_cfg.tool.realm_bin)
    if not rule.direct_ipv6 and global_cfg.ingress.listen_interface and not realm_info.supports_listen_interface:
        raise PreflightError(f"Realm {realm_info.version_text} 不支持监听网卡绑定，请使用支持 --listen-interface 的版本")
    link_states, addr_map = get_local_network_state()
    ipv6_addr_map = get_local_ipv6_addresses() if (rule.direct_ipv6 or line.is_ipv6) else None
    listen_iface = verify_local_listen_ip(rule.listen_ip, addr_map, ipv6_addr_map=ipv6_addr_map)
    verify_line_interface_and_source(line, link_states, addr_map, ipv6_addr_map=ipv6_addr_map)
    route_res = verify_egress_route(line, rule.remote_ip)
    return_route = _verify_return_route(global_cfg, rule.listen_ip, listen_iface, link_states, addr_map)

    _check_managed_rule_port_conflicts(global_cfg, rule)

    allowed_pids = set()
    try:
        props = systemd_show(unit_name)
        main_pid = int(props.get("MainPID", "0") or "0")
        if props.get("ActiveState") == "active" and main_pid > 0:
            allowed_pids.add(main_pid)
    except Exception:
        pass

    listeners = list_tcp_listeners()
    conflicts = find_port_conflicts(
        listen_ip=rule.listen_ip,
        listen_port=rule.listen_port,
        listeners=listeners,
        allowed_pids=allowed_pids,
    )
    if conflicts:
        raise PreflightError(format_port_conflict_error(rule.listen_ip, rule.listen_port, conflicts))

    return PreflightReport(
        rule=rule,
        line=line,
        realm_info=realm_info,
        listen_interface=listen_iface,
        route_result=route_res,
        unit_name=unit_name,
        fixed_ip_check=fixed_check,
        stale_ip_warning=stale_warn,
        return_route=return_route,
    )


def _compute_plan_action(
    global_cfg: GlobalConfig,
    rule: RuleConfig,
    realm_info: RealmBinaryInfo,
) -> Tuple[str, Dict[str, str]]:
    paths = _rule_paths(global_cfg, rule.name)
    desired_rule_toml = render_rule_toml(rule)
    desired_realm_toml = render_realm_toml(rule, global_cfg.lines[rule.line], global_cfg.ingress.listen_interface)
    desired_realm_env = _render_realm_env(realm_info.path)

    if not paths["stored_rule"].exists():
        action = "CREATE"
    else:
        same_rule = paths["stored_rule"].read_text(encoding="utf-8") == desired_rule_toml
        applied = _load_state_json(paths["state_json"]).get("applied_line")
        same_line = applied == asdict(global_cfg.lines[rule.line])
        same_realm = (
            paths["realm_toml"].is_file()
            and paths["realm_toml"].read_text(encoding="utf-8") == desired_realm_toml
            and paths["realm_env"].is_file()
            and paths["realm_env"].read_text(encoding="utf-8") == desired_realm_env
        )
        unit = unit_name_for_rule(global_cfg.tool.systemd_unit_template, rule.name)
        is_up = systemd_is_enabled(unit) and systemd_is_active(unit)
        if same_rule and same_line and same_realm and is_up:
            action = "NOOP"
        elif same_realm and is_up:
            action = "UPDATE_METADATA"
        else:
            action = "UPDATE"

    return action, {
        "rule_toml": desired_rule_toml,
        "realm_toml": desired_realm_toml,
        "realm_env": desired_realm_env,
    }


def plan_rule(
    global_cfg: GlobalConfig,
    rule_file: Union[str, RuleConfig],
    check_dns: bool = False,
    allow_non_dns: bool = False,
    dns_server: str = "",
) -> Dict[str, Any]:
    """Read-only preview and preflight verification of applying a rule file."""
    rule = rule_file if isinstance(rule_file, RuleConfig) else load_rule_config(
        rule_file, default_domain=global_cfg.ingress.default_domain
    )
    if rule.remote_is_ipv6:
        raise ConfigError("已停止创建或修改 IPv6 落地转发，请使用 IPv4 落地地址")
    report = preflight_rule(
        global_cfg,
        rule,
        check_dns=check_dns,
        allow_non_dns=allow_non_dns,
        dns_server=dns_server,
    )
    action, rendered = _compute_plan_action(global_cfg, rule, report.realm_info)
    paths = _rule_paths(global_cfg, rule.name)

    return {
        "action": action,
        "rule_name": rule.name,
        "unit_name": report.unit_name,
        "line": asdict(report.line),
        "line_family": report.line.family,
        "listen_interface": report.listen_interface,
        "bound_listen_interface": (global_cfg.ingress.listen_interface if not rule.direct_ipv6 else ""),
        "realm": {
            "path": report.realm_info.path,
            "version": report.realm_info.version_text,
            "origin": report.realm_info.origin,
            "sha256": report.realm_info.sha256,
        },
        "route_check": {
            "kind": "kernel_route_lookup",
            "command": " ".join(report.route_result.command),
            "raw_output": report.route_result.raw_output,
            "dev": report.route_result.dev,
            "via": report.route_result.via,
            "table": report.route_result.table,
        },
        "return_route": report.return_route.raw_output if report.return_route else "",
        "target_paths": {k: str(v) for k, v in paths.items()},
        "dial_hint": rule.dial_addr,
        "public_port": rule.public_port,
        "listen": rule.listen_endpoint,
        "remote": rule.remote_endpoint,
        "remote_family": rule.remote_family,
        "through": report.line.source_ip,
        "egress_interface": report.line.interface,
        "forced_non_dns": bool(report.fixed_ip_check and report.fixed_ip_check.forced_override),
        "stale_ip_warning": report.stale_ip_warning,
        "rendered_realm_toml": rendered["realm_toml"],
    }


def _verify_unit_running_and_listening(
    unit_name: str,
    listen_ip: str,
    listen_port: int,
    timeout: float = 5.0,
    baseline_restarts: int = 0,
) -> int:
    """Wait for unit to become active, verify socket ownership, and re-check stability."""
    deadline = time.monotonic() + timeout
    last_props: Dict[str, str] = {}
    verified_pid = 0

    while time.monotonic() < deadline:
        last_props = systemd_show(unit_name)
        active = last_props.get("ActiveState", "")
        sub = last_props.get("SubState", "")
        main_pid = int(last_props.get("MainPID", "0") or "0")
        restarts = int(last_props.get("NRestarts", "0") or "0")

        if active == "failed" or restarts > baseline_restarts:
            raise SystemdError(
                f"systemd 单元启动失败: ActiveState={active}, SubState={sub}, "
                f"NRestarts={restarts} (baseline={baseline_restarts})"
            )

        if active == "active" and sub == "running" and main_pid > 0:
            listeners = list_tcp_listeners()
            for sock in listeners:
                if sock.ip == listen_ip and sock.port == listen_port:
                    if any(proc.pid == main_pid for proc in sock.procs):
                        verified_pid = main_pid
                        break
            if verified_pid:
                break
        time.sleep(0.2)

    if not verified_pid:
        raise SystemdError(
            f"在 {timeout:.1f}s 内未观察到 {unit_name} 监听 {format_endpoint(listen_ip, listen_port)} (状态: {last_props})"
        )

    time.sleep(0.35)
    settle = systemd_show(unit_name)
    if (
        settle.get("ActiveState") != "active"
        or settle.get("SubState") != "running"
        or int(settle.get("MainPID", "0") or "0") != verified_pid
        or int(settle.get("NRestarts", "0") or "0") > baseline_restarts
    ):
        raise SystemdError(f"systemd 单元稳定期校验失败: {settle}")

    return verified_pid


def _snapshot_file(path: Path) -> Optional[str]:
    if path.is_file() and not path.is_symlink():
        return path.read_text(encoding="utf-8")
    return None


def _restore_file_safe(path: Path, previous: Optional[str], mode: int = 0o644) -> Optional[str]:
    """Restore or remove a single file, returning an error string only on failure."""
    try:
        if previous is None:
            if path.exists():
                path.unlink()
        else:
            atomic_write_text(path, previous, mode=mode)
        return None
    except Exception as exc:
        return f"恢复文件 {path} 失败: {exc}"


def _rollback_written_files(
    written_keys: List[str],
    paths: Dict[str, Path],
    prev_files: Dict[str, Optional[str]],
    state_dir: str,
    prev_registry: Optional[Dict[str, Any]],
    registry_mutated: bool,
) -> Tuple[List[str], List[str]]:
    """Roll back only files & registry entries that were actually written."""
    restored: List[str] = []
    errors: List[str] = []
    for key in reversed(written_keys):
        err = _restore_file_safe(paths[key], prev_files[key], mode=0o644)
        if err:
            errors.append(err)
        else:
            restored.append(f"{key}({paths[key]})")
    if registry_mutated:
        try:
            if prev_registry is None:
                reg_p = Path(state_dir) / "managed-rules.json"
                if reg_p.exists():
                    reg_p.unlink()
            else:
                save_managed_rules_registry(state_dir, prev_registry)
            restored.append("managed-rules.json")
        except Exception as exc:
            errors.append(f"恢复受管清单失败: {exc}")
    return restored, errors


def _rollback_creation_stage2(
    unit_name: str,
    rule_name: str,
    written_keys: List[str],
    paths: Dict[str, Path],
    state_dir: str,
    prev_registry: Optional[Dict[str, Any]],
    registry_mutated: bool,
) -> List[str]:
    """Fault-tolerant rollback when first-time rule creation fails in systemd stage."""
    notes: List[str] = []
    stop_err: Optional[str] = None
    disable_err: Optional[str] = None

    try:
        systemd_stop(unit_name)
    except Exception as exc:
        stop_err = str(exc)
        notes.append(f"停止单元时出错（继续后续检查与恢复）: {stop_err}")

    try:
        systemd_disable(unit_name, now=False)
    except Exception as exc:
        disable_err = str(exc)
        notes.append(f"禁用单元时出错（继续后续检查与恢复）: {disable_err}")

    try:
        systemd_reset_failed(unit_name)
    except Exception:
        pass

    active_now: Optional[bool] = None
    try:
        active_now = systemd_is_active(unit_name)
    except Exception:
        active_now = None

    # A failed status query is distinct from a confirmed inactive unit. Keep
    # the generated files and ownership record whenever the final state is
    # not proven inactive.
    still_running = active_now is not False
    if still_running:
        notes.append(
            f"回滚未完全完成：无法确认单元 {unit_name} 已停止，已保留其依赖的运行/规则文件及归属记录以便人工检查（未孤立运行进程）"
        )
        return notes

    removed: List[str] = []
    file_errs: List[str] = []
    for key in reversed(written_keys):
        err = _restore_file_safe(paths[key], None)
        if err:
            file_errs.append(err)
        else:
            removed.append(str(paths[key]))

    if registry_mutated:
        try:
            if prev_registry is None:
                unregister_managed_rule(state_dir, rule_name)
            else:
                save_managed_rules_registry(state_dir, prev_registry)
        except Exception as exc:
            file_errs.append(f"清理受管清单条目失败: {exc}")

    if stop_err or disable_err or file_errs:
        notes.append(
            f"已确认 {unit_name} 未在运行；已清理文件: {', '.join(removed) or '(无)'}"
        )
        if file_errs:
            notes.append(f"残留/清理失败项: {'；'.join(file_errs)}")
    else:
        notes.append("首次创建失败，已停用单元并清理本次生成的规则与运行文件")
    return notes


def _rollback_update_stage2(
    global_cfg: GlobalConfig,
    unit_name: str,
    prev_enabled: bool,
    prev_active: bool,
    written_keys: List[str],
    paths: Dict[str, Path],
    prev_files: Dict[str, Optional[str]],
    prev_registry: Optional[Dict[str, Any]],
    registry_mutated: bool,
) -> List[str]:
    """Fault-tolerant rollback when updating an existing rule fails in systemd stage."""
    notes: List[str] = []
    step_errors: List[str] = []

    try:
        systemd_stop(unit_name)
    except Exception as exc:
        step_errors.append(f"停止单元失败: {exc}")
    try:
        systemd_reset_failed(unit_name)
    except Exception:
        pass

    restored, file_errs = _rollback_written_files(
        written_keys=written_keys,
        paths=paths,
        prev_files=prev_files,
        state_dir=global_cfg.tool.state_dir,
        prev_registry=prev_registry,
        registry_mutated=registry_mutated,
    )
    step_errors.extend(file_errs)
    if restored:
        notes.append(f"已恢复文件: {', '.join(restored)}")

    try:
        if prev_enabled:
            systemd_enable(unit_name)
        else:
            systemd_disable(unit_name, now=False)
    except Exception as exc:
        step_errors.append(f"恢复开机启用状态 ({prev_enabled}) 失败: {exc}")

    if prev_active:
        try:
            systemd_reset_failed(unit_name)
            rb_base = int(systemd_show(unit_name).get("NRestarts", "0") or "0")
            systemd_restart(unit_name)
            old_rule = load_rule_config(
                str(paths["stored_rule"]),
                default_domain=global_cfg.ingress.default_domain,
            )
            _verify_unit_running_and_listening(
                unit_name,
                old_rule.listen_ip,
                old_rule.listen_port,
                timeout=5.0,
                baseline_restarts=rb_base,
            )
            notes.append("已恢复原有规则配置、启用状态并重新拉起原运行实例")
        except Exception as exc:
            step_errors.append(f"重新拉起原运行实例失败: {exc}")
    else:
        try:
            systemd_stop(unit_name)
            systemd_reset_failed(unit_name)
            if not step_errors:
                notes.append("已恢复原有规则配置与停用状态")
        except Exception as exc:
            step_errors.append(f"确认停用原单元失败: {exc}")

    if step_errors:
        notes.append(f"回滚部分步骤失败（请检查残留状态）: {'；'.join(step_errors)}")
    return notes


def apply_rule(
    global_cfg: GlobalConfig,
    rule_file: Union[str, RuleConfig],
    lock_timeout: float = 15.0,
    allow_non_dns: bool = False,
    dns_server: str = "",
    expected_rule: Optional[RuleConfig] = None,
    create_only: bool = False,
) -> Dict[str, Any]:
    """Deploy or update a forwarding rule idempotently with staged commits and fault-tolerant rollback."""
    lock_file = resolve_lock_file(global_cfg=global_cfg)
    with FileLock(lock_file, timeout=lock_timeout):
        _assert_live_install_intact(global_cfg)
        rule = rule_file if isinstance(rule_file, RuleConfig) else load_rule_config(
            rule_file, default_domain=global_cfg.ingress.default_domain
        )
        if rule.remote_is_ipv6:
            raise ConfigError("已停止创建或修改 IPv6 落地转发，请使用 IPv4 落地地址")
        paths = _rule_paths(global_cfg, rule.name)
        stored = paths["stored_rule"]
        if create_only and stored.exists():
            raise ApplyError(f"规则 {rule.name!r} 已存在，请使用编辑")
        if expected_rule is not None and (
            not stored.is_file()
            or load_rule_config(str(stored), default_domain=global_cfg.ingress.default_domain) != expected_rule
        ):
            raise ApplyError(f"规则 {rule.name!r} 已变更，请重新预览")
        report = preflight_rule(
            global_cfg,
            rule,
            check_dns=False,
            allow_non_dns=allow_non_dns,
            dns_server=dns_server,
        )
        action, rendered = _compute_plan_action(global_cfg, rule, report.realm_info)
        unit_name = report.unit_name

        bound_listen_iface = global_cfg.ingress.listen_interface if not rule.direct_ipv6 else ""
        if action == "NOOP":
            props = systemd_show(unit_name)
            main_pid = int(props.get("MainPID", "0") or "0")
            listeners = list_tcp_listeners()
            listening = any(
                s.ip == rule.listen_ip
                and s.port == rule.listen_port
                and any(p.pid == main_pid for p in s.procs)
                for s in listeners
            )
            if props.get("ActiveState") == "active" and props.get("SubState") == "running" and listening:
                register_managed_rule(global_cfg.tool.state_dir, global_cfg.tool.rules_dir, rule.name, unit_name)
                return {
                    "status": "noop",
                    "changed": False,
                    "rule_name": rule.name,
                    "unit_name": unit_name,
                    "main_pid": main_pid,
                    "line": rule.line,
                    "line_family": report.line.family,
                    "listen": rule.listen_endpoint,
                    "listen_interface": report.listen_interface,
                    "bound_listen_interface": bound_listen_iface,
                    "remote": rule.remote_endpoint,
                    "remote_family": rule.remote_family,
                    "through": report.line.source_ip,
                    "egress_interface": report.line.interface,
                    "dial_addr": rule.dial_addr,
                    "public_port": rule.public_port,
                    "realm_bin": report.realm_info.path,
                    "realm_version": report.realm_info.version_text,
                    "stale_ip_warning": report.stale_ip_warning,
                    "forced_non_dns": bool(report.fixed_ip_check and report.fixed_ip_check.forced_override),
                }
            action = "UPDATE"

        existed = paths["stored_rule"].exists()
        prev_files = {k: _snapshot_file(p) for k, p in paths.items()}
        prev_registry = load_managed_rules_registry(global_cfg.tool.state_dir)
        prev_enabled = systemd_is_enabled(unit_name) if existed else False
        prev_active = systemd_is_active(unit_name) if existed else False

        now_utc = datetime.now(timezone.utc).isoformat()
        state_payload = {
            "rule_name": rule.name,
            "line": rule.line,
            "line_family": report.line.family,
            "applied_line": asdict(report.line),
            "enabled": True,
            "unit_name": unit_name,
            "realm_bin": report.realm_info.path,
            "realm_version": report.realm_info.version_text,
            "realm_origin": report.realm_info.origin,
            "listen": rule.listen_endpoint,
            "listen_interface": bound_listen_iface,
            "remote": rule.remote_endpoint,
            "remote_family": rule.remote_family,
            "through": report.line.source_ip,
            "egress_interface": report.line.interface,
            "public_port": rule.public_port,
            "ingress_domain": rule.ingress_domain,
            "ingress_fixed_ip": rule.ingress_fixed_ip,
            "applied_at_utc": now_utc,
        }
        state_text = json.dumps(state_payload, ensure_ascii=False, indent=2) + "\n"

        # Fast safe metadata-only update (e.g. changing ingress.fixed_ip / description) without touching live Realm!
        if action == "UPDATE_METADATA":
            props = systemd_show(unit_name)
            main_pid = int(props.get("MainPID", "0") or "0")
            written_keys: List[str] = []
            reg_mutated = False
            try:
                atomic_write_text(paths["stored_rule"], rendered["rule_toml"], mode=0o644)
                written_keys.append("stored_rule")
                atomic_write_text(paths["state_json"], state_text, mode=0o644)
                written_keys.append("state_json")
                register_managed_rule(global_cfg.tool.state_dir, global_cfg.tool.rules_dir, rule.name, unit_name)
                reg_mutated = True
            except Exception as meta_exc:
                restored, errs = _rollback_written_files(
                    written_keys=written_keys,
                    paths=paths,
                    prev_files=prev_files,
                    state_dir=global_cfg.tool.state_dir,
                    prev_registry=prev_registry,
                    registry_mutated=reg_mutated,
                )
                msg = (
                    f"更新规则 {rule.name!r} 元数据失败（未触动运行中的 Realm 与已有连接）: {meta_exc}"
                )
                if restored:
                    msg += f"\n--- 回滚结果 ---\n已恢复: {', '.join(restored)}"
                if errs:
                    msg += f"\n回滚出错: {'；'.join(errs)}"
                raise ApplyError(msg) from meta_exc

            return {
                "status": "metadata-updated",
                "changed": True,
                "realm_restarted": False,
                "rule_name": rule.name,
                "unit_name": unit_name,
                "main_pid": main_pid,
                "line": rule.line,
                "line_family": report.line.family,
                "interface": report.line.interface,
                "gateway": report.line.gateway,
                "table": report.line.table,
                "listen": rule.listen_endpoint,
                "listen_interface": report.listen_interface,
                "bound_listen_interface": bound_listen_iface,
                "remote": rule.remote_endpoint,
                "remote_family": rule.remote_family,
                "through": report.line.source_ip,
                "egress_interface": report.line.interface,
                "dial_addr": rule.dial_addr,
                "public_port": rule.public_port,
                "realm_bin": report.realm_info.path,
                "realm_version": report.realm_info.version_text,
                "route_output": report.route_result.raw_output,
                "stale_ip_warning": report.stale_ip_warning,
                "forced_non_dns": bool(report.fixed_ip_check and report.fixed_ip_check.forced_override),
            }

        # Stage 1: File commits (if any write fails here, DO NOT touch running systemd service!).
        written_keys = []
        reg_mutated = False
        file_plan = [
            ("stored_rule", paths["stored_rule"], rendered["rule_toml"]),
            ("realm_toml", paths["realm_toml"], rendered["realm_toml"]),
            ("realm_env", paths["realm_env"], rendered["realm_env"]),
            ("state_json", paths["state_json"], state_text),
        ]
        try:
            for key, path, content in file_plan:
                atomic_write_text(path, content, mode=0o644)
                written_keys.append(key)
            register_managed_rule(global_cfg.tool.state_dir, global_cfg.tool.rules_dir, rule.name, unit_name)
            reg_mutated = True
        except Exception as write_exc:
            restored, errs = _rollback_written_files(
                written_keys=written_keys,
                paths=paths,
                prev_files=prev_files,
                state_dir=global_cfg.tool.state_dir,
                prev_registry=prev_registry,
                registry_mutated=reg_mutated,
            )
            if not written_keys:
                rb_note = "首次写入即失败，未改动磁盘文件，也未中断原有运行实例与连接"
            else:
                rb_note = f"仅回滚已写入文件: {', '.join(restored)}（未触动原有运行实例与连接）"
            if errs:
                rb_note += f"；回滚错误: {'；'.join(errs)}"
            raise ApplyError(f"应用规则 {rule.name!r} 写入阶段失败: {write_exc}\n--- 回滚结果 ---\n{rb_note}") from write_exc

        # Stage 2: Service commit & verification
        try:
            systemd_enable(unit_name)
            systemd_reset_failed(unit_name)
            pre_restarts = int(systemd_show(unit_name).get("NRestarts", "0") or "0")
            systemd_restart(unit_name)
            main_pid = _verify_unit_running_and_listening(
                unit_name, rule.listen_ip, rule.listen_port, baseline_restarts=pre_restarts
            )
        except Exception as svc_exc:
            try:
                journal_tail = systemd_journal_tail(unit_name, lines=15)
            except Exception as j_exc:
                journal_tail = f"(日志采集失败，已跳过继续执行恢复: {j_exc})"

            if not existed:
                rollback_notes = _rollback_creation_stage2(
                    unit_name=unit_name,
                    rule_name=rule.name,
                    written_keys=written_keys,
                    paths=paths,
                    state_dir=global_cfg.tool.state_dir,
                    prev_registry=prev_registry,
                    registry_mutated=reg_mutated,
                )
            else:
                rollback_notes = _rollback_update_stage2(
                    global_cfg=global_cfg,
                    unit_name=unit_name,
                    prev_enabled=prev_enabled,
                    prev_active=prev_active,
                    written_keys=written_keys,
                    paths=paths,
                    prev_files=prev_files,
                    prev_registry=prev_registry,
                    registry_mutated=reg_mutated,
                )

            detail = f"应用规则 {rule.name!r} 失败: {svc_exc}"
            if journal_tail:
                detail += f"\n--- journalctl ---\n{journal_tail}"
            detail += f"\n--- 回滚结果 ---\n{'; '.join(rollback_notes)}"
            raise ApplyError(detail) from svc_exc

        return {
            "status": "created" if action == "CREATE" else "updated",
            "changed": True,
            "realm_restarted": True,
            "rule_name": rule.name,
            "unit_name": unit_name,
            "main_pid": main_pid,
            "line": rule.line,
            "line_family": report.line.family,
            "interface": report.line.interface,
            "gateway": report.line.gateway,
            "table": report.line.table,
            "listen": rule.listen_endpoint,
            "listen_interface": report.listen_interface,
            "bound_listen_interface": bound_listen_iface,
            "remote": rule.remote_endpoint,
            "remote_family": rule.remote_family,
            "through": report.line.source_ip,
            "egress_interface": report.line.interface,
            "dial_addr": rule.dial_addr,
            "public_port": rule.public_port,
            "realm_bin": report.realm_info.path,
            "realm_version": report.realm_info.version_text,
            "route_output": report.route_result.raw_output,
            "stale_ip_warning": report.stale_ip_warning,
            "forced_non_dns": bool(report.fixed_ip_check and report.fixed_ip_check.forced_override),
        }


def verify_startup_rule(
    global_cfg: GlobalConfig,
    rule_name: str,
    wait_timeout: Optional[float] = None,
) -> Dict[str, Any]:
    """Systemd ExecStartPre check: wait until line interface, source IP, policy/egress route, and return route are ready."""
    validate_rule_name(rule_name)
    _assert_rule_owned_for_mutation(global_cfg, rule_name)
    paths = _rule_paths(global_cfg, rule_name)
    if not paths["stored_rule"].is_file():
        raise ConfigError(f"启动前检查失败，缺少规则文件: {paths['stored_rule']}")
    rule = load_rule_config(str(paths["stored_rule"]), default_domain=global_cfg.ingress.default_domain)
    state = _load_state_json(paths["state_json"])
    line = _applied_line(global_cfg, rule, state)
    if line is None:
        raise PreflightError(f"启动前检查失败，线路 {rule.line!r} 不在主配置中")
    if rule.remote_is_ipv6 != line.is_ipv6:
        raise PreflightError(
            f"启动前检查失败，规则 {rule.name!r} 落地地址族 ({rule.remote_family}) 与线路 {rule.line!r} ({line.family}) 不匹配"
        )

    if not paths["realm_toml"].is_file():
        raise ConfigError(f"启动前检查失败，缺少 Realm 运行配置: {paths['realm_toml']}")
    realm_lines = paths["realm_toml"].read_text(encoding="utf-8", errors="replace").splitlines()
    expected_remote = f'remote = "{rule.remote_endpoint}"'
    expected_through = f'through = "{format_realm_through(line.source_ip)}"'
    expected_iface = f'interface = "{line.interface}"'
    if expected_remote not in realm_lines or expected_through not in realm_lines or expected_iface not in realm_lines:
        raise PreflightError(
            f"Realm 运行配置 ({paths['realm_toml']}) 未同时绑定 {expected_remote}、{expected_through} 与 {expected_iface}，拒绝启动"
        )
    ingress_iface = _applied_listen_interface(global_cfg, rule, state)
    if rule.direct_ipv6:
        if f'listen = "{rule.listen_endpoint}"' not in realm_lines:
            raise PreflightError(f"Realm 运行配置缺少公网监听 {rule.listen_endpoint}，请重新应用规则")
        if any(ln.startswith("listen_interface = ") for ln in realm_lines):
            raise PreflightError("IPv6 直连规则的 Realm 运行配置不应绑定 listen_interface，请重新应用规则")
    elif ingress_iface and f'listen_interface = "{ingress_iface}"' not in realm_lines:
        raise PreflightError(f"Realm 运行配置缺少入口网卡绑定 {ingress_iface}，请重新应用规则")

    applied_cfg = replace(global_cfg, ingress=replace(global_cfg.ingress, listen_interface=ingress_iface))
    max_wait = float(
        global_cfg.tool.startup_route_wait_seconds if wait_timeout is None else max(0.0, wait_timeout)
    )
    deadline = time.monotonic() + max_wait
    last_err = ""
    while True:
        try:
            link_states, addr_map = get_local_network_state()
            ipv6_addr_map = get_local_ipv6_addresses() if (rule.direct_ipv6 or line.is_ipv6) else None
            listen_iface = verify_local_listen_ip(rule.listen_ip, addr_map, ipv6_addr_map=ipv6_addr_map)
            verify_line_interface_and_source(line, link_states, addr_map, ipv6_addr_map=ipv6_addr_map)
            route_res = verify_egress_route(line, rule.remote_ip)
            return_route = _verify_return_route(applied_cfg, rule.listen_ip, listen_iface, link_states, addr_map)
            return {
                "rule_name": rule.name,
                "line": line.name,
                "line_family": line.family,
                "interface": line.interface,
                "source_ip": line.source_ip,
                "gateway": line.gateway,
                "table": line.table,
                "remote": rule.remote_endpoint,
                "route_output": route_res.raw_output,
                "return_route": return_route.raw_output,
            }
        except Exception as exc:
            last_err = str(exc)
            if time.monotonic() >= deadline:
                raise PreflightError(
                    f"等待线路 {line.name!r} 出口路由就绪超时 ({max_wait:.1f}s): {last_err}"
                ) from exc
            time.sleep(0.5)


def list_managed_rules(global_cfg: GlobalConfig) -> List[RuleConfig]:
    """Load all owned rule configs currently stored in rules_dir."""
    rules_dir = Path(global_cfg.tool.rules_dir)
    if not rules_dir.is_dir():
        return []
    rules: List[RuleConfig] = []
    for path in sorted(rules_dir.glob("*.toml")):
        try:
            kind, _ = check_rule_ownership(
                rules_dir=global_cfg.tool.rules_dir,
                state_dir=global_cfg.tool.state_dir,
                rule_name=path.stem,
                unit_template=global_cfg.tool.systemd_unit_template,
            )
            if kind != "unowned":
                rules.append(load_rule_config(str(path), default_domain=global_cfg.ingress.default_domain))
        except (ConfigError, OwnershipError):
            continue
    return rules


def _inspect_single_rule_status(
    global_cfg: GlobalConfig,
    rule: RuleConfig,
    listeners: List[Any],
    check_dns: bool = False,
    link_states: Optional[Dict[str, Tuple[str, List[str]]]] = None,
    addr_map: Optional[Dict[str, List[str]]] = None,
    ipv6_addr_map: Optional[Dict[str, List[LocalIpv6Addr]]] = None,
    net_error: str = "",
) -> Dict[str, Any]:
    unit_name = unit_name_for_rule(global_cfg.tool.systemd_unit_template, rule.name)
    props = systemd_show(unit_name)
    enabled = systemd_is_enabled(unit_name)
    active_state = props.get("ActiveState", "unknown")
    sub_state = props.get("SubState", "unknown")
    main_pid = int(props.get("MainPID", "0") or "0")
    restarts = int(props.get("NRestarts", "0") or "0")

    listening_ok = any(
        s.ip == rule.listen_ip
        and s.port == rule.listen_port
        and main_pid > 0
        and any(p.pid == main_pid for p in s.procs)
        for s in listeners
    )

    state_data = _load_state_json(_rule_paths(global_cfg, rule.name)["state_json"])
    desired_line = global_cfg.lines.get(rule.line)
    bound_listen_iface = _applied_listen_interface(global_cfg, rule, state_data)
    desired_listen_iface = "" if rule.direct_ipv6 else global_cfg.ingress.listen_interface
    line_cfg = None
    route_ok = False
    route_detail = ""
    try:
        line_cfg = _applied_line(global_cfg, rule, state_data)
        if line_cfg is None:
            raise PreflightError(f"缺少线路 {rule.line!r} 的已应用记录")
        if net_error:
            raise PreflightError(net_error)
        if link_states is not None and addr_map is not None:
            verify_line_interface_and_source(line_cfg, link_states, addr_map, ipv6_addr_map=ipv6_addr_map)
        rt = verify_egress_route(line_cfg, rule.remote_ip)
        route_ok = True
        route_detail = rt.raw_output
    except (ConfigError, PreflightError) as exc:
        route_detail = str(exc)

    pending_network = {}
    if desired_line is None:
        pending_network["line_removed"] = True
    elif line_cfg and _line_route_settings(desired_line) != _line_route_settings(line_cfg):
        pending_network["line"] = asdict(desired_line)
    if desired_listen_iface != bound_listen_iface:
        pending_network["listen_interface"] = desired_listen_iface

    stale_warning = None
    if check_dns and rule.ingress_fixed_ip:
        dns_res = query_dns_a(domain=rule.ingress_domain, dns_server=global_cfg.ingress.dns_server)
        stale_warning = check_fixed_ip_staleness(rule.ingress_fixed_ip, rule.ingress_domain, dns_res)

    return {
        "rule_name": rule.name,
        "description": rule.description,
        "line": rule.line,
        "line_family": line_cfg.family if line_cfg else "",
        "line_description": line_cfg.description if line_cfg else "",
        "unit_name": unit_name,
        "enabled": enabled,
        "active_state": active_state,
        "sub_state": sub_state,
        "main_pid": main_pid,
        "n_restarts": restarts,
        "listening_ok": listening_ok,
        "route_ok": route_ok,
        "route_check_kind": "kernel_route_lookup",
        "route_detail": route_detail,
        "pending_network": pending_network,
        "listen": rule.listen_endpoint,
        "listen_interface": bound_listen_iface,
        "remote": rule.remote_endpoint,
        "remote_family": rule.remote_family,
        "through": line_cfg.source_ip if line_cfg else "",
        "egress_interface": line_cfg.interface if line_cfg else "",
        "egress_gateway": line_cfg.gateway if line_cfg else "",
        "egress_table": line_cfg.table if line_cfg else None,
        "public_port": rule.public_port,
        "ingress_domain": rule.ingress_domain,
        "ingress_fixed_ip": rule.ingress_fixed_ip,
        "dial_addr": rule.dial_addr,
        "realm_bin": state_data.get("realm_bin", ""),
        "realm_version": state_data.get("realm_version", ""),
        "stale_ip_warning": stale_warning,
    }


def status_rules(
    global_cfg: GlobalConfig,
    rule_name: Optional[str] = None,
    check_dns: bool = False,
) -> List[Dict[str, Any]]:
    """Inspect runtime, systemd, socket, and route status for one or all owned managed rules."""
    listeners = list_tcp_listeners()
    if rule_name:
        validate_rule_name(rule_name)
        _assert_rule_owned_for_mutation(global_cfg, rule_name)
        rule_path = _rule_paths(global_cfg, rule_name)["stored_rule"]
        if not rule_path.is_file():
            raise ConfigError(f"未找到托管规则: {rule_name} ({rule_path})")
        rules = [load_rule_config(str(rule_path), default_domain=global_cfg.ingress.default_domain)]
    else:
        rules = list_managed_rules(global_cfg)

    link_states: Optional[Dict[str, Tuple[str, List[str]]]] = None
    addr_map: Optional[Dict[str, List[str]]] = None
    ipv6_addr_map: Optional[Dict[str, List[LocalIpv6Addr]]] = None
    net_error = ""
    if rules:
        try:
            link_states, addr_map = get_local_network_state()
            needs_v6 = any(
                r.direct_ipv6
                or r.remote_is_ipv6
                or (r.line in global_cfg.lines and global_cfg.lines[r.line].is_ipv6)
                for r in rules
            )
            if needs_v6:
                ipv6_addr_map = get_local_ipv6_addresses()
        except PreflightError as exc:
            net_error = str(exc)

    return [
        _inspect_single_rule_status(
            global_cfg,
            r,
            listeners,
            check_dns=check_dns,
            link_states=link_states,
            addr_map=addr_map,
            ipv6_addr_map=ipv6_addr_map,
            net_error=net_error,
        )
        for r in rules
    ]


def disable_rule(
    global_cfg: GlobalConfig,
    rule_name: str,
    lock_timeout: float = 15.0,
) -> Dict[str, Any]:
    """Stop and disable an owned forwarding rule while keeping its config for future apply."""
    validate_rule_name(rule_name)
    lock_file = resolve_lock_file(global_cfg=global_cfg)
    with FileLock(lock_file, timeout=lock_timeout):
        _assert_rule_owned_for_mutation(global_cfg, rule_name)
        paths = _rule_paths(global_cfg, rule_name)
        if not paths["stored_rule"].is_file():
            raise ConfigError(f"未找到托管规则: {rule_name} ({paths['stored_rule']})")
        unit_name = unit_name_for_rule(global_cfg.tool.systemd_unit_template, rule_name)
        systemd_disable(unit_name, now=True)
        systemd_stop(unit_name)
        systemd_reset_failed(unit_name)

        state = _load_state_json(paths["state_json"])
        state["enabled"] = False
        state["disabled_at_utc"] = datetime.now(timezone.utc).isoformat()
        atomic_write_text(paths["state_json"], json.dumps(state, ensure_ascii=False, indent=2) + "\n")
        return {
            "rule_name": rule_name,
            "unit_name": unit_name,
            "enabled": False,
            "active_state": systemd_show(unit_name).get("ActiveState", "inactive"),
            "kept_config": str(paths["stored_rule"]),
        }


def delete_rule(
    global_cfg: GlobalConfig,
    rule_name: str,
    lock_timeout: float = 15.0,
) -> Dict[str, Any]:
    """Stop, disable, and delete ONLY this owned rule's managed files."""
    validate_rule_name(rule_name)
    lock_file = resolve_lock_file(global_cfg=global_cfg)
    with FileLock(lock_file, timeout=lock_timeout):
        _assert_rule_owned_for_mutation(global_cfg, rule_name)
        paths = _rule_paths(global_cfg, rule_name)
        if not any(p.exists() for p in paths.values()):
            raise ConfigError(f"未找到托管规则或状态文件: {rule_name}")
        unit_name = unit_name_for_rule(global_cfg.tool.systemd_unit_template, rule_name)
        systemd_disable(unit_name, now=True)
        systemd_stop(unit_name)
        systemd_reset_failed(unit_name)

        removed: List[str] = []
        for path in paths.values():
            if path.exists():
                path.unlink()
                removed.append(str(path))
        unregister_managed_rule(global_cfg.tool.state_dir, rule_name)
        return {
            "rule_name": rule_name,
            "unit_name": unit_name,
            "removed_files": removed,
        }


def _write_ingress_settings(paths: Dict[str, Path], rule: RuleConfig, selected_at: str = "") -> None:
    state_path = paths["state_json"]
    previous_state = _snapshot_file(state_path)
    state = _load_state_json(state_path)
    state["ingress_domain"] = rule.ingress_domain
    state["ingress_fixed_ip"] = rule.ingress_fixed_ip
    if selected_at:
        state["ingress_selected_at_utc"] = selected_at
    else:
        state.pop("ingress_selected_at_utc", None)
    state_text = json.dumps(state, ensure_ascii=False, indent=2) + "\n"
    rule_text = render_rule_toml(rule)
    try:
        atomic_write_text(state_path, state_text)
    except OSError as exc:
        raise ApplyError(f"写入规则 {rule.name!r} 的入口状态失败: {exc}") from exc
    try:
        atomic_write_text(paths["stored_rule"], rule_text)
    except OSError as exc:
        error = _restore_file_safe(state_path, previous_state)
        detail = f"；{error}" if error else ""
        raise ApplyError(f"写入规则 {rule.name!r} 的入口配置失败: {exc}{detail}") from exc


def select_rule_ingress_ip(
    global_cfg: GlobalConfig,
    rule_name: str,
    ip: str,
    domain: Optional[str] = None,
    dns_server: str = "",
    allow_non_dns: bool = False,
    probe: bool = False,
    verify_send: str = "",
    verify_expect: str = "",
    tls: bool = False,
    tls_sni: str = "",
    tls_cafile: str = "",
    tls_insecure: bool = False,
    timeout: float = 3.0,
    lock_timeout: float = 15.0,
    expected_rule: Optional[RuleConfig] = None,
) -> Dict[str, Any]:
    """Explicitly pin a public ingress IP using unified candidate validation without touching Realm listen/PID."""
    from .config import validate_ipv4

    validate_rule_name(rule_name)
    validated_ip = validate_ipv4(ip, "ingress_ip")
    lock_file = resolve_lock_file(global_cfg=global_cfg)
    with FileLock(lock_file, timeout=lock_timeout):
        _assert_rule_owned_for_mutation(global_cfg, rule_name)
        paths = _rule_paths(global_cfg, rule_name)
        if not paths["stored_rule"].is_file():
            raise ConfigError(f"未找到已托管规则: {rule_name} ({paths['stored_rule']})")
        old_rule = load_rule_config(
            str(paths["stored_rule"]), default_domain=global_cfg.ingress.default_domain
        )
        if old_rule.direct_ipv6:
            raise ConfigError("公网 IPv6 直连入口请通过编辑规则更改监听地址")
        if expected_rule is not None and old_rule != expected_rule:
            raise ApplyError(f"规则 {rule_name!r} 已变更，请重新预览")
        target_domain = domain.strip() if domain else old_rule.ingress_domain
        effective_dns = dns_server or global_cfg.ingress.dns_server

        prev_for_check = old_rule.ingress_fixed_ip if target_domain == old_rule.ingress_domain else ""
        check = evaluate_fixed_ip_policy(
            domain=target_domain,
            new_fixed_ip=validated_ip,
            prev_fixed_ip=prev_for_check,
            dns_server=effective_dns,
            allow_non_dns=allow_non_dns,
            timeout=timeout,
        )
        if not check.allowed:
            raise ConfigError(check.error or "固定公网 IP 校验失败")

        probe_res = None
        if probe or verify_send or verify_expect or tls or tls_sni:
            probe_res = probe_candidate(
                ip=validated_ip,
                port=old_rule.public_port,
                in_dns=check.in_dns,
                timeout=timeout,
                send_payload=verify_send,
                expect_pattern=verify_expect,
                tls=tls,
                tls_sni=tls_sni,
                tls_insecure=tls_insecure,
                tls_cafile=tls_cafile,
            )

        updated_rule = replace(old_rule, ingress_domain=target_domain, ingress_fixed_ip=validated_ip)
        _write_ingress_settings(paths, updated_rule, selected_at=check.dns_result.queried_at_utc)

        return {
            "rule_name": rule_name,
            "domain": target_domain,
            "queried_at_local": check.dns_result.queried_at_local,
            "queried_at_utc": check.dns_result.queried_at_utc,
            "dns_ips": check.dns_result.ips,
            "dns_failed": check.dns_failed,
            "in_dns": check.in_dns,
            "forced_override": check.forced_override,
            "warning": check.warning,
            "selected_ip": validated_ip,
            "public_port": updated_rule.public_port,
            "dial_address": f"{validated_ip}:{updated_rule.public_port}",
            "realm_listen": updated_rule.listen_endpoint,
            "realm_restarted": False,
            "probe": asdict(probe_res) if probe_res else None,
            "protocol_notes": protocol_preservation_notes(validated_ip, updated_rule.public_port, target_domain),
        }


